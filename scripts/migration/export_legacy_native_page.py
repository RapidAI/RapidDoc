def groups():
    import copy,math,random
    from rapid_doc.utils.pdf_text_tool import (_legacy_chars_to_page_chars,_materialize_page_chars,
        _deduplicate_adjacent_offset_chars,get_lines_from_chars,get_blocks)
    from pdftext.pdf.chars import deduplicate_chars
    from pdftext.schema import Bbox
    target=ROOT/'build/migration/legacy-native-groups.json'
    if target.exists():raise FileExistsError(target)
    def normalize(v):
        if isinstance(v,Bbox):return v.bbox
        if isinstance(v,dict):return {k:normalize(x)for k,x in v.items()}
        if isinstance(v,(list,tuple)):return [normalize(x)for x in v]
        return v
    def char(c,x,y,h=10.,font=0,rotation=0.):
        return dict(char=c,bbox=[float(x),float(y),float(x+5),float(y+h)],rotation=rotation,
            font=dict(name='Helvetica',flags=font,size=10.+font,weight=400),char_idx=0)
    cases=[]
    def add(chars):
        for i,c in enumerate(chars):c['char_idx']=i
        request=dict(size=[200.,200.],bbox=[0.,0.,200.,200.],width=200,height=200,rotation=0,char_count=len(chars),chars=copy.deepcopy(chars))
        old=_materialize_page_chars(deduplicate_chars(_legacy_chars_to_page_chars(chars)))
        old=_deduplicate_adjacent_offset_chars(old)
        expected={k:v for k,v in request.items()if k!='char_count'}
        expected.update(chars=old,blocks=get_blocks(get_lines_from_chars(old)))
        cases.append(dict(request=request,expected=normalize(expected)))
    add([])
    for symbol in ['2','²','½','Ⅻ','+','∑','𝟘','\u1c89','\U0001e5f1','a','\x1c','\u200b',' ','\n','\x02']:
        for y in [0.,3.,7.,10.,13.,17.]:
            add([char('x',0,10),char(symbol,6,y,6.,1),char('y',12,10)])
    for angle in [0.,-0.,math.pi/4,math.nextafter(math.pi/4,0),math.nextafter(math.pi/4,math.inf),math.pi*3/4,math.pi,math.pi*2,math.pi*2+math.pi/4]:
        add([char('a',0,10),char('b',6,10,rotation=angle),char('c',12,10)])
    for offset in [0.,.5,1.,1.00000000000001,1.5,2.5,2.500000000000001,3.]:
        add([char('a',0,10),char('a',offset,10+offset)])
    r=random.Random(491)
    for _ in range(160):
        chars=[]
        for i in range(r.randrange(1,45)):
            chars.append(char(r.choice('ab 22\n\x02'),r.randrange(0,20)*5,r.randrange(0,10)*10,r.choice([0.,4.,10.]),r.randrange(3),r.choice([0.,0.,math.pi/2,math.pi])))
        add(chars)
    write_json(target,dict(cases=cases))
    print(f'Frozen {len(cases)} actual old dedup/group boundary references')

if __name__=='__main__':main()
