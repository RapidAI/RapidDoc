def unicode_tables():
    assert unicodedata.unidata_version=='16.0.0'
    out=['// Generated by export_legacy_native_page.py; CPython Unicode 16.0.0 properties.']
    for name,test in [('digit',str.isdigit),('alnum',str.isalnum),('math',lambda c:unicodedata.category(c)=='Sm')]:
        ranges=[];start=None
        for i in range(0x110001):
            okay=i<0x110000 and test(chr(i))
            if okay and start is None:start=i
            if not okay and start is not None:ranges.append((start,i-1));start=None
        out.append(f'pub(super) fn {name}(c:char)->bool {{ let n=c as u32; {name.upper()}.binary_search_by(|&(a,b)| if b<n {{std::cmp::Ordering::Less}} else if a>n {{std::cmp::Ordering::Greater}} else {{std::cmp::Ordering::Equal}}).is_ok() }}')
        out.append(f'const {name.upper()}: &[(u32,u32)] = &['+', '.join(f'(0x{a:x},0x{b:x})'for a,b in ranges)+'];')
    (ROOT/'rust/rapiddoc-pdf/src/legacy_chars/grouping/unicode.rs').write_text('\n'.join(out)+'\n',encoding='utf-8')

