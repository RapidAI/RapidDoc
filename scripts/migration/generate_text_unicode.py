"""固定文本换行规则使用的 Python Unicode 类别；运行时无需 Python/unicodedata。"""
import sys,unicodedata
from common import ROOT,write_json,digest

def main():
    ranges=[];start=0;previous=0
    for value in range(0x110001):
        flags=0
        if value<0x110000:
            char=chr(value);category=unicodedata.category(char)
            flags=int(char.isspace())|2*int(char.islower())|4*int(char.isdigit())|8*int(category=='Nd')
            flags|=16*int(category[0]in'MC')|32*int(category in('Ps','Pi'))|64*int(category in('Pe','Pf'))|128*int(char.isalnum())
            flags|=256*int(char.isupper())|512*int(char.isalpha())
        if flags!=previous:
            if previous:ranges.append((start,value-1,previous))
            start=value;previous=flags
    source='//! Generated by scripts/migration/generate_text_unicode.py; Python Unicode '+unicodedata.unidata_version+'.\n'
    source+='pub(super) const RANGES: &[(u32,u32,u16)] = &[\n'+''.join(f'    (0x{a:X},0x{b:X},{f}),\n'for a,b,f in ranges)+'];\n'
    (ROOT/'rust/rapiddoc-native/src/text_unicode_data.rs').write_text(source,encoding='utf-8')
    write_json(ROOT/'packaging/text-unicode-provenance.json',dict(python=sys.version,unicode=unicodedata.unidata_version,ranges=len(ranges),
        generator='scripts/migration/generate_text_unicode.py',generator_sha256=digest((ROOT/'scripts/migration/generate_text_unicode.py').read_bytes()),
        flags='1=space,2=lower,4=digit,8=Nd,16=mark/control,32=opening,64=closing,128=alnum,256=upper,512=alpha'))
    print(f'Generated {len(ranges)} text Unicode ranges ({unicodedata.unidata_version})')
if __name__=='__main__':main()
