r"""固定当前 Python 的字符类别，用于视觉权重、strip 与正则 \d；运行时不调用 Python。"""
import sys,unicodedata
from common import ROOT,write_json,digest

def main():
    spans=[];start=None;previous=0
    for value in range(0x110001):
        if value==0x110000:flags=0
        else:
            char=chr(value);flags=int(char.isalpha()or char.isdigit())+2*int(char.isspace())+4*int(unicodedata.category(char)=="Nd")
        if flags!=previous:
            if previous:spans.append((start,value-1,previous))
            start=value;previous=flags
    source='//! Generated by scripts/migration/generate_table_unicode.py; Python Unicode '+unicodedata.unidata_version+'.\n'
    source+='pub(crate) const RANGES: &[(u32,u32,u8)] = &[\n'+''.join(f'    (0x{a:X},0x{b:X},{f}),\n'for a,b,f in spans)+'];\n'
    path=ROOT/'rust/rapiddoc-inference/src/table/unicode_data.rs';path.write_text(source,encoding='utf-8')
    write_json(ROOT/'packaging/table-unicode-provenance.json',dict(python=sys.version,unicode=unicodedata.unidata_version,generator='scripts/migration/generate_table_unicode.py',generator_sha256=digest((ROOT/'scripts/migration/generate_table_unicode.py').read_bytes()),semantic='1=isalpha or isdigit,2=isspace,4=Nd; ranges omit zero flags',ranges=len(spans)))
    print(f'Generated {len(spans)} Unicode flag ranges ({unicodedata.unidata_version})')

if __name__=='__main__':main()
